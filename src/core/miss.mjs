/**
 * 「没翻到」其实有四种。
 *
 * ── 为什么要拆 ──
 *
 * `fish_recall` 翻不到的时候，我原来只回一句「这一句没翻到。可能是真没有，
 * 也可能我当时用了别的说法」—— 听着诚实，其实把四种完全不同的情况
 * 糊成了一句含糊话：
 *
 *   1. 库是空的          → 不是没翻到，是还没有
 *   2. 模型读过说没有    → 它懂意思，它说没有，那字面上沾边的不算数
 *   3. 被日期裁掉了      → 那条在，只是不在这个窗口里
 *   4. 真没有            → 库里这些字一个都没出现过
 *
 * 而这两天我干的每一件事 —— 记不清分档、作废标记、原话库的「有 / 没有」——
 * 核心就是**不许含糊**。最该说清楚的地方反而最含糊，这说不过去。
 *
 * ── 抄自哪儿 ──
 *
 * `dsh-emotion-memory` 的 `lib/index.js:389` 与 `:422` 会把检索落空分成
 * 「没过门槛 / 没有候选（字面没对上） / 这几条刚给过」。它的整体我没装
 * （理由见 CHANGELOG 1.20.0 之后那段），但**这一条它是对的**：
 * 失败的原因比失败本身有用。
 *
 * ── 措辞的规矩 ──
 *
 * 不说"系统未找到匹配项"，也不说"检索失败"。说的是：库里有没有、
 * 差在哪个环节、下一步该怎么办。前三个我都能确认，第四个只在我
 * 真扫过之后才说得出口。
 */

/**
 * @param {object} p
 * @param {number} p.total 库里一共有多少条
 * @param {number} p.loose 字面上沾边的条数（不分日期、不看门槛）
 * @param {number} p.inLoose 其中落在查询窗口里的条数
 * @param {boolean} p.hasRange 这次查询有没有限定日期
 * @param {boolean} p.modelSaidNo 模型读过语料，明确说"没有"
 * @param {string} p.query
 * @returns {string}
 */
export function diagnoseMiss({
  total = 0,
  loose = 0,
  inLoose = 0,
  hasRange = false,
  modelSaidNo = false,
  query = '',
} = {}) {
  const q = String(query ?? '').trim();
  const quoted = q === '' ? '' : `「${q}」`;

  // 1. 库是空的。这不是"没翻到" —— 是还没有东西可翻。
  if (total <= 0) {
    return '档案现在还是空的，一条日记都没有 —— 这不是没翻到，是还没有。';
  }

  // 3. 被日期裁掉了。这条最容易被误读成"他没说过"，所以先于"模型说没有"报：
  //    只要放宽日期就有，那就不是没有。
  if (hasRange && loose > 0 && inLoose === 0) {
    return `那段时间里没有${quoted}，但整份档案里有 ${loose} 条沾得上 —— `
      + '是日期把它裁掉了，不是没发生过。放宽日期再看一次。';
  }

  // 2. 模型读过语料，它说没有。字面沾边的不算数 —— 但得让我知道有这回事。
  if (modelSaidNo) {
    return loose > 0
      ? `我读了一遍，没有对得上${quoted}的。字面上有 ${loose} 条沾边，但沾边不是记得 —— `
        + '要按字面翻，就换个更实的词再查一次。'
      : `我读了一遍，没有对得上${quoted}的，字面上也没有一个词沾边。就当他没说过，别编一个像样的。`;
  }

  // 3'. 有沾边但都落在窗口外 / 字面全空 —— 分开说。
  if (loose > 0) {
    return `库里 ${total} 条，字面上有 ${loose} 条沾${quoted}的边，但没一条真的对上。`
      + '换个更实的词（人名、物件、数字）再试一次。';
  }

  // 4. 真没有。这句可以说得硬 —— 因为我真的扫过（有日期窗口的话，窗口内外都扫了）。
  const scope = hasRange ? `那段时间、以及它前后，一共 ${total} 条日记里` : `${total} 条日记里`;
  return `没有。${scope}没有跟${quoted}对得上的字 —— 不是"我记不太清"，是档案里没有。`
    + '（但查不到不等于他没说过：我记的是经过，不是原话。要原话走 fish_quote。）';
}
